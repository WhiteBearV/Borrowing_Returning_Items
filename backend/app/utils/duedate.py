"""วันครบกำหนดคืน "ที่ใช้จริง" ของอุปกรณ์ 1 ชิ้น — ต้องมีที่เดียวในระบบ

ตั้งแต่เฟส 3 วันครบกำหนดอยู่ได้ 3 ที่ (ต่อเวลาที่อนุมัติแล้ว · วันของชิ้นนี้ · วันของทั้งใบ)
ถ้าปล่อยให้แต่ละจุด coalesce เอง (scheduler ทวงวันหนึ่ง หน้าเว็บโชว์อีกวัน ใบยืมพิมพ์อีกวัน)
ผู้ยืมจะโดนทวงผิดวันแน่นอน — ทุกจุดต้องเรียกฟังก์ชันนี้

ใช้ getattr เพราะถูกเรียกทั้งกับ ORM (BorrowItem) และ Pydantic (BorrowItemResponse) และกับ
object ที่เทส/พรีวิวประกอบขึ้นเองซึ่งอาจไม่มีฟิลด์ครบ
"""
from datetime import date


def effective_due_date(item: object, req: object = None) -> date | None:
    """ลำดับความสำคัญ: ต่อเวลาที่อนุมัติแล้ว > วันของชิ้นนี้ > วันของทั้งคำขอ

    req ส่งมาเพื่อใช้เป็นค่าถอยหลังสุดท้าย (คำขอเก่าก่อนเฟส 3 ที่ยังไม่มีวันรายชิ้น)
    """
    return (
        getattr(item, "extended_due_date", None)
        or getattr(item, "due_date", None)
        or getattr(req, "due_date", None)
    )


def fmt_date(d: date | None) -> str:
    """วันที่ในข้อความแจ้งเตือน/อีเมล เป็น วว/ดด/ปปปป ให้ตรงกับหน้าเว็บ (formatDate)

    ใส่ date ลง f-string ตรง ๆ จะได้ 2026-09-21 ซึ่งผู้ใช้อ่านสลับวัน/เดือนได้
    """
    return f"{d:%d/%m/%Y}" if d else "-"
