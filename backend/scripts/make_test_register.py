"""ปั๊มไฟล์ทะเบียนทดสอบ จากไฟล์ทะเบียนจริง — ใช้ลองฟีเจอร์ "นำเข้าจาก Excel"

ก๊อปไฟล์ทะเบียนจริง (โครงคอลัมน์/ชีตเหมือนเดิมทุกอย่าง) แล้วแกล้งแก้ให้เหมือน
ทะเบียนรอบใหม่ที่ส่งมาจากงานพัสดุ: มีของชำรุด มีของหาย มีของซื้อเข้ามาใหม่

Usage:
    python backend/scripts/make_test_register.py

Output:
    Report/ทดสอบนำเข้า-ทะเบียนรอบใหม่.xlsx
    → อัปโหลดในหน้า "จัดการอุปกรณ์" > นำเข้าจาก Excel ควรได้ร่าง:
      อัปเดต 3 (ชำรุด 1 / สูญหาย 1 / ย้ายห้อง 1) · เพิ่มใหม่ 3 · ไม่พบในไฟล์ 3 · ข้าม 1 (ไม่มีเลข)
      โดยของใหม่ชิ้นที่ 3 ตั้งใจพิมพ์ชื่อผิด ("กล่องเว็บแคม") ไว้ให้ลองแก้ในหน้าร่างก่อนบันทึก
"""
import os
import shutil

import openpyxl

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(
    ROOT, "docs",
    "รายงานทะเบียนคุมทรัพย์สิน - คณะเทคโนโลยีดิจิทัล ข้อมูล ณ วันที่ 4 พฤศจิกายน 2568.xlsx",
)
DST = os.path.join(ROOT, "Report", "ทดสอบนำเข้า-ทะเบียนรอบใหม่.xlsx")

# ครุภัณฑ์ที่ "ซื้อเข้ามาใหม่" — คอลัมน์ตามชีตคณะ: ลำดับ, รหัส, ชื่อ, ราคา, วันที่รับ, ปกติ, ...
# ชิ้นสุดท้ายจงใจพิมพ์ชื่อผิด ไว้ให้ทดสอบการแก้ในหน้าร่างก่อนบันทึก
NEW_ITEMS = [
    ("68-213-001-001-0001", "เครื่องพิมพ์ 3 มิติ Creality Ender-3", 8900, "15311"),
    ("68-213-002-001-0001", "ออสซิลโลสโคป Rigol DS1054Z", 25000, "15311"),
    ("68-213-003-001-0001", "กล่องเว็บแคม Logitech C920", 3500, "15312"),
]


# วัสดุ (ชีต "วัสดุ") — คอลัมน์: รหัส, รายการ, ประเภท, หน่วยนับ, จำนวน, สถานที่จัดเก็บ
# ไม่มีในทะเบียนคุมทรัพย์สิน (วัสดุไม่ต้องออกเลขครุภัณฑ์) จึงใช้รหัสภายในของคลัง
MATERIAL_ITEMS = [
    ("MAT-ARD-001", "บอร์ด Arduino UNO R3", "วัสดุใช้ซ้ำ", "ชิ้น", 25, "15310"),
    ("MAT-ESP-001", "บอร์ด ESP32 DevKit", "วัสดุใช้ซ้ำ", "ชิ้น", 15, "15310"),
    ("CON-WIRE-001", "สายไฟจัมเปอร์ ผู้-ผู้ (คละสี)", "วัสดุสิ้นเปลือง", "ชุด", 40, "15310"),
    (None, "ตัวต้านทานคละค่า (ยังไม่ออกรหัส)", "วัสดุสิ้นเปลือง", "ถุง", 10, "15310"),  # ไม่มีรหัส → ระบบต้องข้าม
]


def main() -> None:
    shutil.copy(SRC, DST)
    wb = openpyxl.load_workbook(DST)
    ws = wb["คณะเทคโนฯดิจิทัล"]  # ข้อมูลเริ่มแถว 5, คอลัมน์: 2 รหัส, 3 ชื่อ, 6 ปกติ, 7 ชำรุด, 9 สูญหาย, 12 สถานที่

    # 1) เครื่องที่ 2 ชำรุด — ย้ายเครื่องหมายจากช่อง "ปกติ" ไป "ชำรุด"
    ws.cell(row=6, column=6).value = None
    ws.cell(row=6, column=7).value = "P"

    # 2) เครื่องที่ 3 สูญหาย (ไม่พบตัวจริงตอนตรวจนับ)
    ws.cell(row=7, column=6).value = None
    ws.cell(row=7, column=9).value = "P"

    # 3) เครื่องที่ 4 ย้ายห้องเก็บ
    ws.cell(row=8, column=12).value = "15399"

    # 4) ลบ 3 แถวออกจากทะเบียน = ของที่หายไปจากทะเบียน (ระบบเสนอปลดระวาง แต่ไม่ทำเองจนกว่าจะติ๊ก)
    ws.delete_rows(9, 3)

    # 5) ของใหม่ต่อท้าย + 1 แถวที่ยังไม่ได้ออกเลขครุภัณฑ์ (ระบบต้องข้ามและรายงานให้เห็น)
    for i, (code, name, price, loc) in enumerate(NEW_ITEMS, 1):
        ws.append([9000 + i, code, name, price, None, "P", None, None, None, None,
                   "คณะเทคโนโลยีดิจิทัล", loc])
    ws.append([9999, None, "จอภาพ 27 นิ้ว (ยังไม่ออกเลขครุภัณฑ์)", 6500, None, "P", None, None, None, None,
               "คณะเทคโนโลยีดิจิทัล", "15312"])

    # 6) ชีต "วัสดุ" — วัสดุไม่มีในทะเบียนคุมทรัพย์สิน จึงใช้ชีตแยก รูปแบบง่าย ๆ (header แถว 1)
    ws2 = wb.create_sheet("วัสดุ")
    ws2.append(["รหัส", "รายการ", "ประเภท", "หน่วยนับ", "จำนวน", "สถานที่จัดเก็บ"])
    for row in MATERIAL_ITEMS:
        ws2.append(list(row))

    wb.save(DST)
    print(f"สร้างแล้ว: {DST}")
    print("คาดว่าร่างจะได้: อัปเดต 3 · เพิ่มใหม่ 3 + วัสดุใหม่ 3 · ไม่พบในไฟล์ 3 · ข้าม 1 (ไม่มีรหัส)")


if __name__ == "__main__":
    main()
